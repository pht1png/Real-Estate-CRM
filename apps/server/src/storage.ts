import { mkdir } from "node:fs/promises";
import path from "node:path";
import { S3Client } from "bun";

/**
 * Object storage for floor plans and other uploads (brief §3): a local folder
 * in dev/tests, S3-compatible storage (e.g. Cloudflare R2) in production.
 * Files are only ever served through short-lived signed URLs.
 */
export interface FileStorage {
	put(key: string, data: Blob, contentType: string): Promise<void>;
	url(key: string, expiresInSeconds?: number): Promise<string>;
}

const DEFAULT_EXPIRY = 60 * 60;

async function hmac(secret: string, value: string) {
	const key = await crypto.subtle.importKey(
		"raw",
		new TextEncoder().encode(secret),
		{ name: "HMAC", hash: "SHA-256" },
		false,
		["sign"],
	);
	const sig = await crypto.subtle.sign(
		"HMAC",
		key,
		new TextEncoder().encode(value),
	);
	return Buffer.from(sig).toString("base64url");
}

/** Keys are generated by the server; reject anything that could escape the folder. */
export function isSafeKey(key: string) {
	return /^[a-zA-Z0-9][a-zA-Z0-9/_.-]*$/.test(key) && !key.includes("..");
}

export function createLocalStorage(options: {
	dir: string;
	publicUrl: string;
	secret: string;
}) {
	const root = path.resolve(options.dir);
	const base = options.publicUrl.replace(/\/$/, "");
	const fileFor = (key: string) => {
		if (!isSafeKey(key)) throw new Error("Invalid storage key");
		return path.join(root, key);
	};

	return {
		async put(key, data) {
			const file = fileFor(key);
			await mkdir(path.dirname(file), { recursive: true });
			await Bun.write(file, data);
		},
		async url(key, expiresInSeconds = DEFAULT_EXPIRY) {
			const exp = Math.floor(Date.now() / 1000) + expiresInSeconds;
			const sig = await hmac(options.secret, `${key}:${exp}`);
			return `${base}/files/local/${key}?exp=${exp}&sig=${sig}`;
		},
		/** Resolves a signed local URL to the file, or null when invalid/expired. */
		async verify(
			key: string,
			exp: string | undefined,
			sig: string | undefined,
		) {
			if (!exp || !sig || !isSafeKey(key)) return null;
			if (Number(exp) < Date.now() / 1000) return null;
			if ((await hmac(options.secret, `${key}:${exp}`)) !== sig) return null;
			const file = Bun.file(fileFor(key));
			return (await file.exists()) ? file : null;
		},
	} satisfies FileStorage & Record<string, unknown>;
}

export function createS3Storage(options: {
	endpoint: string;
	bucket: string;
	accessKeyId: string;
	secretAccessKey: string;
}): FileStorage {
	const client = new S3Client(options);
	return {
		async put(key, data, contentType) {
			await client.write(key, data, { type: contentType });
		},
		async url(key, expiresInSeconds = DEFAULT_EXPIRY) {
			return client.presign(key, { expiresIn: expiresInSeconds });
		},
	};
}
